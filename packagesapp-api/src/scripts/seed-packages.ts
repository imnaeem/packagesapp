async function seedPackages(): Promise<void> {
  initFirebase();
  const db = getDb();

  const existing = await db.collection('packages').limit(1).get();
  if (!existing.empty) {
    console.log('Packages already seeded, skipping.');
    return;
  }

  const batch = db.batch();
  for (const pkg of SEED_PACKAGES) {
    const ref = db.collection('packages').doc();
    batch.set(ref, {
      ...pkg,
      createdAt: admin.firestore.FieldValue.serverTimestamp(),
      updatedAt: admin.firestore.FieldValue.serverTimestamp(),
    });
  }
  await batch.commit();
  console.log(`✅ Seeded ${SEED_PACKAGES.length} packages successfully`);
}

seedPackages()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('❌ Seed failed:', err);
    process.exit(1);
  });
